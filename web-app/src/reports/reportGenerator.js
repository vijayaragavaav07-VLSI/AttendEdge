// Date / time helpers
export const D = {
  parse: s => {
    const [y, m, d] = s.split('-').map(Number);
    return new Date(Date.UTC(y, m - 1, d));
  },
  fmt: dt => `${dt.getUTCFullYear()}-${String(dt.getUTCMonth() + 1).padStart(2, '0')}-${String(dt.getUTCDate()).padStart(2, '0')}`,
  add: (s, n) => {
    const dt = D.parse(s);
    dt.setUTCDate(dt.getUTCDate() + n);
    return D.fmt(dt);
  },
  dow: s => D.parse(s).getUTCDay(),
  valid: s => /^\d{4}-\d{2}-\d{2}$/.test(s || '') && !isNaN(D.parse(s)),
  range: (a, b) => {
    const o = [];
    let d = a;
    let i = 0;
    while (d <= b && i < 900) {
      o.push(d);
      d = D.add(d, 1);
      i++;
    }
    return o;
  },
  weekStart: s => D.add(s, -((D.dow(s) + 6) % 7)),
  long: s => D.parse(s).toLocaleDateString('en-GB', { weekday: 'long', day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' }),
  med: s => D.parse(s).toLocaleDateString('en-GB', { day: 'numeric', month: 'short', year: 'numeric', timeZone: 'UTC' }),
  short: s => D.parse(s).toLocaleDateString('en-GB', { weekday: 'short', day: 'numeric', month: 'short', timeZone: 'UTC' }),
  dayName: s => D.parse(s).toLocaleDateString('en-GB', { weekday: 'long', timeZone: 'UTC' }),
  mon: (y, m) => new Date(Date.UTC(y, m - 1, 1)).toLocaleDateString('en-GB', { month: 'long', year: 'numeric', timeZone: 'UTC' }),
  monShort: (y, m) => new Date(Date.UTC(y, m - 1, 1)).toLocaleDateString('en-GB', { month: 'short', timeZone: 'UTC' }),
  monthRange: (y, m) => [`${y}-${String(m).padStart(2, '0')}-01`, D.fmt(new Date(Date.UTC(y, m, 0)))],
  firstMonday: s => {
    let d = s;
    while (D.dow(d) !== 1) d = D.add(d, 1);
    return d;
  }
};

export const pad = n => String(n).padStart(2, '0');
export const toSec = t => {
  const p = String(t).split(':').map(Number);
  return p[0] * 3600 + (p[1] || 0) * 60 + (p[2] || 0);
};
export const hms = sec => `${pad(Math.floor(sec / 3600))}:${pad(Math.floor((sec % 3600) / 60))}:${pad(sec % 60)}`;
export const t12 = t => {
  if (!t) return '—';
  const p = String(t).split(':').map(Number);
  const ap = p[0] >= 12 ? 'PM' : 'AM';
  return `${p[0] % 12 || 12}:${pad(p[1] || 0)}${p.length > 2 ? ':' + pad(p[2]) : ''} ${ap}`;
};
export const pctText = v => (v === null || v === undefined ? 'Not Available' : v.toFixed(1) + '%');

const pdfSafe = s => String(s == null ? '' : s).replace(/[\u2010-\u2015\u2212]/g, '-').replace(/[\u2190-\u2193]/g, '->').replace(/\u2026/g, '...');
const csvCell = v => {
  const s = String(v == null ? '' : v);
  return /[",\n\r]/.test(s) ? '"' + s.replace(/"/g, '""') + '"' : s;
};
const toCSV = rows => rows.map(r => r.map(csvCell).join(',')).join('\r\n');

export function downloadBlob(blob, filename) {
  const a = document.createElement('a');
  a.href = URL.createObjectURL(blob);
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  setTimeout(() => {
    URL.revokeObjectURL(a.href);
    a.remove();
  }, 800);
}

export function exportCSV(report) {
  const allRows = [
    ['AttendEdge', report.title],
    ...(report.meta || []),
    ...(report.summary || []),
    [],
    report.columns,
    ...report.rows
  ];
  const blob = new Blob(['\ufeff' + toCSV(allRows)], { type: 'text/csv;charset=utf-8' });
  downloadBlob(blob, `${report.file}.csv`);
}

export function printReport(report) {
  const tbl = `<table><thead><tr>${report.columns.map(c => `<th>${c}</th>`).join('')}</tr></thead><tbody>${report.rows.map(r => `<tr>${r.map(c => `<td>${c}</td>`).join('')}</tr>`).join('')}</tbody></table>`;
  const html = `<!doctype html><html><head><meta charset="utf-8"><title>${report.file}</title><style>
    body{font:13px/1.45 Arial,Helvetica,sans-serif;color:#1B2340;margin:24px}
    h1{font-size:23px;color:#505BD4;margin:0}.sub{color:#5C6178;margin-bottom:14px;border-bottom:1px solid #E6E1D8;padding-bottom:10px}
    h2{font-size:17px;margin:12px 0 6px}p{margin:2px 0;color:#464B5F}.sum{margin:10px 0;font-weight:bold}
    table{border-collapse:collapse;width:100%;margin-top:10px}th{background:#505BD4;color:#fff;text-align:left}
    th,td{border:1px solid #D3CCBE;padding:5px 8px;font-size:12px}tr:nth-child(even) td{background:#FAF8F5}
    .foot{margin-top:14px;font-size:11px;color:#5C6178}@page{margin:14mm}
  </style></head><body>
    <h1>AttendEdge</h1><div class="sub">Smart Attendance Management · Verilog FSM System</div>
    <h2>${report.title}</h2>
    ${(report.meta || []).map(m => `<p>${m[0]}: ${m[1]}</p>`).join('')}
    ${report.summary && report.summary.length ? `<p class="sum">${report.summary.map(s => s[0] + ': ' + s[1]).join('  |  ')}</p>` : ''}
    ${tbl}
    <p class="foot">Generated by AttendEdge Smart Attendance Management System.</p>
  </body></html>`;

  const iframe = document.createElement('iframe');
  iframe.setAttribute('aria-hidden', 'true');
  iframe.style.cssText = 'position:fixed;right:0;bottom:0;width:0;height:0;border:0';
  document.body.appendChild(iframe);
  iframe.onload = () => {
    setTimeout(() => {
      try {
        iframe.contentWindow.focus();
        iframe.contentWindow.print();
      } catch (e) {
        console.error(e);
      }
      setTimeout(() => iframe.remove(), 5000);
    }, 200);
  };
  iframe.srcdoc = html;
}

export function exportPDF(report) {
  try {
    const doc = new jsPDF({
      unit: 'pt',
      format: 'a4',
      orientation: report.columns.length > 5 ? 'landscape' : 'portrait'
    });

    const W = doc.internal.pageSize.getWidth();
    const H = doc.internal.pageSize.getHeight();
    const M = 40;
    let y = 48;

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(21);
    doc.setTextColor(80, 91, 212);
    doc.text('AttendEdge', M, y);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9.5);
    doc.setTextColor(92, 97, 120);
    doc.text('Smart Attendance Management · FSM & Flip-Flop Architecture', M, y + 14);

    doc.setDrawColor(214, 208, 196);
    doc.line(M, y + 24, W - M, y + 24);
    y += 50;

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(16);
    doc.setTextColor(27, 35, 64);
    doc.text(pdfSafe(report.title), M, y);
    y += 19;

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9.5);
    doc.setTextColor(60, 65, 85);
    (report.meta || []).forEach(m => {
      doc.text(pdfSafe(`${m[0]}: ${m[1]}`), M, y);
      y += 13;
    });

    if (report.summary && report.summary.length) {
      y += 5;
      doc.setFont('helvetica', 'bold');
      doc.setTextColor(27, 35, 64);
      const summaryText = report.summary.map(s => `${s[0]}: ${s[1]}`).join('   |   ');
      const lines = doc.splitTextToSize(pdfSafe(summaryText), W - 2 * M);
      doc.text(lines, M, y);
      y += lines.length * 13;
    }

    doc.autoTable({
      startY: y + 8,
      head: [report.columns.map(pdfSafe)],
      body: report.rows.map(r => r.map(pdfSafe)),
      styles: { fontSize: 8.5, cellPadding: 4, textColor: [27, 35, 64] },
      headStyles: { fillColor: [80, 91, 212], textColor: 255 },
      alternateRowStyles: { fillColor: [250, 248, 245] },
      margin: { left: M, right: M, bottom: 40 }
    });

    const pageCount = doc.internal.getNumberOfPages();
    for (let i = 1; i <= pageCount; i++) {
      doc.setPage(i);
      doc.setFontSize(8);
      doc.setTextColor(92, 97, 120);
      doc.text('AttendEdge Smart Attendance Management System', M, H - 22);
      doc.text(`Page ${i} of ${pageCount}`, W - M, H - 22, { align: 'right' });
    }

    doc.save(`${report.file}.pdf`);
  } catch (err) {
    console.warn('PDF autoTable failed, falling back to print view:', err);
    printReport(report);
  }
}
